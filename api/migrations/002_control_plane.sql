-- Control-plane schema (previously SQLite control-plane.db, ported 1:1).
--
-- Conventions kept from the SQLite schema so API responses do not change:
--   * timestamps are TEXT (ISO-8601 written by the API, or 'YYYY-MM-DD HH:MM:SS' UTC defaults);
--   * booleans are INTEGER 0/1;
--   * JSON documents are TEXT.

-- Default for the former SQLite `datetime('now')` columns: same text format, UTC.
CREATE OR REPLACE FUNCTION mfx_utc_now_text() RETURNS text
  LANGUAGE sql STABLE
  AS $$ SELECT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT mfx_utc_now_text()
);
-- SQLite declared email COLLATE NOCASE: uniqueness and lookups are case-insensitive.
CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));

CREATE TABLE edition_catalog (
  id TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  capabilities_json TEXT NOT NULL,
  is_system INTEGER NOT NULL DEFAULT 0,
  row_version INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT NULL,
  updated_by TEXT NULL
);

CREATE TABLE tenants (
  id TEXT PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  display_name TEXT NOT NULL,
  force_min_app_version TEXT NULL,
  force_update_mode TEXT NOT NULL DEFAULT 'inherit',
  force_update_reason TEXT NULL,
  rollout_cohort TEXT NOT NULL DEFAULT 'stable-main',
  update_channel TEXT NOT NULL DEFAULT 'stable',
  offline_grace_hours INTEGER NOT NULL DEFAULT 72,
  trust_revocation_disconnects_immediately INTEGER NOT NULL DEFAULT 0,
  reconnect_requires_fresh_heartbeat INTEGER NOT NULL DEFAULT 1,
  is_initialized INTEGER NOT NULL DEFAULT 0,
  has_demo_data INTEGER NOT NULL DEFAULT 0,
  is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT mfx_utc_now_text(),
  bootstrap_completed_at TEXT NULL,
  bootstrap_method TEXT NULL,
  -- Replaces the SQLite delete trigger edition_catalog_delete_guard (ON DELETE RESTRICT).
  edition TEXT NOT NULL DEFAULT 'core' REFERENCES edition_catalog (id) ON DELETE RESTRICT,
  entitlement_lineage INTEGER NOT NULL DEFAULT 0,
  -- Columns found only on legacy VPS SQLite tenant tables (rollout_channel, policy_defaults_json,
  -- status, status_reason, updated_at, ...), kept verbatim by the SQLite -> Postgres migration.
  legacy_attributes_json TEXT NULL
);

CREATE TABLE license_keys (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  license_key TEXT NOT NULL UNIQUE,
  max_machines INTEGER NOT NULL DEFAULT 1,
  update_channel TEXT NOT NULL DEFAULT 'stable',
  issued_by_user_id INTEGER NULL,
  expires_at TEXT NULL,
  revoked_at TEXT NULL,
  revoked_reason TEXT NULL,
  created_at TEXT NOT NULL DEFAULT mfx_utc_now_text()
);
CREATE INDEX license_keys_tenant_idx ON license_keys (tenant_id, created_at DESC, id DESC);

CREATE TABLE machine_activations (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  license_id TEXT NOT NULL REFERENCES license_keys (id),
  machine_fingerprint TEXT NOT NULL,
  machine_label TEXT NULL,
  app_version TEXT NULL,
  activation_token TEXT NOT NULL,
  activated_at TEXT NOT NULL DEFAULT mfx_utc_now_text(),
  last_seen_at TEXT NOT NULL DEFAULT mfx_utc_now_text(),
  revoked_at TEXT NULL,
  -- 'machine' = revoked by an operator (reinstatable); 'license' = the licence was revoked.
  revocation_kind TEXT NULL CHECK (revocation_kind IN ('machine', 'license')),
  UNIQUE (tenant_id, machine_fingerprint)
);
CREATE INDEX machine_activations_license_idx ON machine_activations (license_id);

CREATE TABLE audit_records (
  record_id TEXT PRIMARY KEY,
  sequence INTEGER NOT NULL UNIQUE,
  occurred_at_rfc3339 TEXT NOT NULL,
  actor_id TEXT NOT NULL,
  action_code TEXT NOT NULL,
  action_category TEXT NOT NULL,
  correlation_id TEXT NOT NULL,
  scope_tenant_id TEXT NULL,
  before_snapshot_sha256 TEXT NULL,
  after_snapshot_sha256 TEXT NULL,
  payload_canonical_sha256 TEXT NOT NULL,
  chain_prev_hash TEXT NULL,
  record_integrity_sha256 TEXT NOT NULL,
  reason_code TEXT NULL,
  approval_correlation_id TEXT NULL,
  entity_refs_json TEXT NOT NULL
);

CREATE TABLE support_tickets (
  ticket_id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  state TEXT NOT NULL,
  severity TEXT NOT NULL,
  affected_module TEXT NOT NULL,
  sync_status_hint TEXT NOT NULL,
  app_version_reported TEXT NOT NULL,
  linked_incident_ids_json TEXT NOT NULL DEFAULT '[]',
  sla_due_rfc3339 TEXT NULL,
  created_at_rfc3339 TEXT NOT NULL
);

CREATE TABLE support_ticket_interventions (
  intervention_id TEXT PRIMARY KEY,
  ticket_id TEXT NOT NULL REFERENCES support_tickets (ticket_id),
  actor_id TEXT NOT NULL,
  action_code TEXT NOT NULL,
  note TEXT NOT NULL,
  from_state TEXT NOT NULL,
  to_state TEXT NOT NULL,
  reason_code TEXT NULL,
  audit_record_id TEXT NOT NULL REFERENCES audit_records (record_id),
  created_at_rfc3339 TEXT NOT NULL
);
CREATE INDEX support_ticket_interventions_ticket_idx ON support_ticket_interventions (ticket_id);

CREATE TABLE diagnostic_bundles (
  bundle_id TEXT PRIMARY KEY,
  created_at_rfc3339 TEXT NOT NULL,
  redaction_profile TEXT NOT NULL
);

CREATE TABLE diagnostic_bundle_artifacts (
  bundle_id TEXT NOT NULL REFERENCES diagnostic_bundles (bundle_id),
  logical_path TEXT NOT NULL,
  sha256 TEXT NOT NULL,
  kind TEXT NOT NULL,
  PRIMARY KEY (bundle_id, logical_path)
);

CREATE TABLE offline_ticket_reconciliation (
  desktop_queue_id TEXT PRIMARY KEY,
  vendor_ticket_id TEXT NULL,
  sync_state TEXT NOT NULL,
  duplicate_of TEXT NULL
);

CREATE TABLE incident_runbooks (
  runbook_id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  summary TEXT NOT NULL,
  first_steps_json TEXT NOT NULL
);

CREATE TABLE cohort_update_policies (
  id TEXT PRIMARY KEY,
  channel TEXT NOT NULL,
  cohort_label TEXT NOT NULL,
  force_min_app_version TEXT NULL,
  force_update_mode TEXT NOT NULL DEFAULT 'off',
  force_update_reason TEXT NULL,
  updated_at_rfc3339 TEXT NOT NULL,
  updated_by_actor_id TEXT NULL,
  UNIQUE (channel, cohort_label)
);

CREATE TABLE tenant_update_policy_history (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  previous_force_min_app_version TEXT NULL,
  previous_force_update_mode TEXT NOT NULL,
  previous_force_update_reason TEXT NULL,
  changed_at_rfc3339 TEXT NOT NULL,
  changed_by_actor_id TEXT NULL,
  reason_code TEXT NULL
);
CREATE INDEX tenant_update_policy_history_tenant_idx
  ON tenant_update_policy_history (tenant_id, changed_at_rfc3339 DESC);

CREATE TABLE cohort_update_policy_history (
  id TEXT PRIMARY KEY,
  channel TEXT NOT NULL,
  cohort_label TEXT NOT NULL,
  previous_force_min_app_version TEXT NULL,
  previous_force_update_mode TEXT NOT NULL,
  previous_force_update_reason TEXT NULL,
  changed_at_rfc3339 TEXT NOT NULL,
  changed_by_actor_id TEXT NULL,
  reason_code TEXT NULL
);

CREATE TABLE idempotency_keys (
  idempotency_key TEXT PRIMARY KEY,
  actor_id TEXT NOT NULL,
  method TEXT NOT NULL,
  path TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  response_status INTEGER NOT NULL,
  response_json TEXT NOT NULL,
  created_at_rfc3339 TEXT NOT NULL
);

CREATE TABLE payment_orders (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants (id),
  license_id TEXT NULL,
  plan TEXT NOT NULL,
  amount DOUBLE PRECISION NOT NULL,
  extra_slots INTEGER NOT NULL DEFAULT 0,
  total_amount DOUBLE PRECISION NOT NULL,
  currency TEXT NOT NULL DEFAULT 'DZD',
  status TEXT NOT NULL DEFAULT 'pending',
  slickpay_invoice_id TEXT NULL,
  slickpay_payment_url TEXT NULL,
  user_info_json TEXT NULL,
  meta_json TEXT NOT NULL DEFAULT '{}',
  paid_at TEXT NULL,
  error_message TEXT NULL,
  created_at TEXT NOT NULL DEFAULT mfx_utc_now_text(),
  updated_at TEXT NOT NULL DEFAULT mfx_utc_now_text()
);
CREATE INDEX idx_payment_orders_tenant ON payment_orders (tenant_id);
CREATE INDEX idx_payment_orders_invoice ON payment_orders (slickpay_invoice_id);
