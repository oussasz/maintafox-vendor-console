/**
 * Builds packages/contracts/src/desktop-ipc.generated.ts from the desktop's own contract file
 * (maintafox-desktop shared/ipc-types.ts, which mirrors the Rust structs): the declarations the
 * console uses (CONSOLE_TYPES) and every exported type they reference, verbatim.
 *
 *   node packages/contracts/scripts/extract-desktop-types.mjs --desktop <maintafox-desktop checkout>
 *   node packages/contracts/scripts/extract-desktop-types.mjs --desktop <checkout> --check
 *
 * --check exits 1 when the committed file differs from what the desktop file gives today (drift):
 * CI runs it against the desktop repository (.github/workflows/ci.yml, contracts-drift).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** The desktop contract types the console imports (add a name here, then regenerate). */
export const CONSOLE_TYPES = [
  "BulkEntitlementOperationRequestV1",
  "OpsAlertV1",
  "PermissionRecord",
  "SignedClaimPreviewV1",
  "SyncFailureDrillDownRowV1",
  "SyncHealthSeverityV1",
  "TenantSyncHealthRowV1",
  "VendorAdminAuditActionCategoryV1",
  "VendorAdminAuditRecordV1",
];

const here = dirname(fileURLToPath(import.meta.url));
const OUTPUT = join(here, "..", "src", "desktop-ipc.generated.ts");
const SOURCE_REL = "shared/ipc-types.ts";

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

/** Every `export interface|type Name` declaration of the file, with its full text. */
function declarations(source) {
  const out = new Map();
  const re = /^export (interface|type) ([A-Za-z0-9_]+)/gm;
  let m;
  while ((m = re.exec(source))) {
    const start = m.index;
    let i = start;
    let depth = 0;
    let end = -1;
    if (m[1] === "interface") {
      i = source.indexOf("{", start);
      for (; i < source.length; i += 1) {
        if (source[i] === "{") depth += 1;
        else if (source[i] === "}") {
          depth -= 1;
          if (depth === 0) {
            end = i + 1;
            break;
          }
        }
      }
    } else {
      for (; i < source.length; i += 1) {
        const c = source[i];
        if (c === "{" || c === "(" || c === "[" || c === "<") depth += 1;
        else if (c === "}" || c === ")" || c === "]" || c === ">") depth -= 1;
        else if (c === ";" && depth === 0) {
          end = i + 1;
          break;
        }
      }
    }
    if (end < 0) throw new Error(`cannot find the end of ${m[2]}`);
    out.set(m[2], source.slice(start, end));
  }
  return out;
}

function extract(source, names) {
  const decls = declarations(source);
  const wanted = new Set();
  const visit = (name) => {
    if (wanted.has(name)) return;
    const text = decls.get(name);
    if (!text) throw new Error(`desktop ${SOURCE_REL} has no exported type ${name}`);
    wanted.add(name);
    const body = text.replace(/^export (interface|type) [A-Za-z0-9_]+/, "");
    for (const ref of body.matchAll(/\b([A-Z][A-Za-z0-9_]*)\b/g)) {
      if (decls.has(ref[1])) visit(ref[1]);
    }
  };
  names.forEach(visit);
  // Keep the desktop file's order so regenerating is stable.
  const ordered = [...decls.keys()].filter((n) => wanted.has(n));
  return [
    "// GENERATED by packages/contracts/scripts/extract-desktop-types.mjs from the desktop's",
    `// ${SOURCE_REL} (mirror of the Rust structs). Do not edit: change the desktop, then regenerate.`,
    "// CI fails when this file and the desktop differ (contracts-drift).",
    "",
    ...ordered.map((n) => `${decls.get(n)}\n`),
  ].join("\n");
}

const desktop = arg("--desktop");
if (!desktop) {
  console.error("usage: node packages/contracts/scripts/extract-desktop-types.mjs --desktop <maintafox-desktop checkout> [--check]");
  process.exit(2);
}
const generated = extract(readFileSync(join(desktop, SOURCE_REL), "utf8").replace(/\r\n/g, "\n"), CONSOLE_TYPES);
if (process.argv.includes("--check")) {
  const committed = readFileSync(OUTPUT, "utf8").replace(/\r\n/g, "\n");
  if (committed !== generated) {
    console.error(`contracts drift: ${OUTPUT} differs from the desktop's ${SOURCE_REL}. Regenerate it (without --check), review, commit.`);
    process.exit(1);
  }
  console.log(`contracts aligned with the desktop's ${SOURCE_REL} (${CONSOLE_TYPES.length} console types)`);
} else {
  writeFileSync(OUTPUT, generated);
  console.log(`wrote ${OUTPUT}`);
}
